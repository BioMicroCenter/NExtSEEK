"""The seed DDL files exist, are well formed, and the bundles model maps one.

Two kinds of file live in startup/seed/sql/. The ones startup/steps/schema_fixups.py
registers are what an install loads. The three `*.curated.sql` files are
generated by `scripts/context_gen.py --emit seed` from `context/` and HELD: no
install step reads them until the curated content is signed off.
`NessieAI/tests/api/test_context_gen.py` owns the generator; this module owns what
an install needs from the files themselves.
"""

